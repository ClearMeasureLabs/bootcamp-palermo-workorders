const { MsEdgeTTS, OUTPUT_FORMAT } = require('msedge-tts');
const fs = require('fs');
const path = require('path');

const VOICE = 'en-US-AndrewNeural';
const FPS = 30;
const AUDIO_HEAD_FRAMES = 18; // 0.6s before speech so the cut is not abrupt
const AUDIO_TAIL_FRAMES = 36; // 1.2s after the last word so nothing is clipped
const BYTES_PER_SECOND = 6000; // 48 kbps CBR from AUDIO_24KHZ_48KBITRATE_MONO_MP3
const outDir = path.join(__dirname, '..', 'public', 'audio');
const timingPath = path.join(__dirname, '..', 'src', 'narrationTiming.ts');

const PROSODY = { rate: '-12%' };

const segments = [
  {
    name: 'intro',
    text:
      'The work-order Room field used to stop at fifty characters. We lengthened it to nine hundred, so staff can store a full location.',
  },
  {
    name: 'before',
    text:
      'Here is the live Work Order form from the Playwright test. Room is now a wrapping text area on the same screen staff already use.',
  },
  {
    name: 'after',
    text:
      'The test typed nine hundred characters into Room, saved the draft, and opened the work order again. The full value was still on this screen.',
  },
  {
    name: 'reject',
    text:
      'Then the test entered nine hundred one characters. Save stayed on this form, with the message that Room cannot exceed nine hundred characters.',
  },
];

function framesForFile(filePath) {
  const seconds = fs.statSync(filePath).size / BYTES_PER_SECOND;
  return AUDIO_HEAD_FRAMES + Math.ceil(seconds * FPS) + AUDIO_TAIL_FRAMES;
}

(async () => {
  fs.mkdirSync(outDir, { recursive: true });
  const frames = {};
  for (const seg of segments) {
    const tts = new MsEdgeTTS();
    await tts.setMetadata(VOICE, OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3);
    const { audioFilePath } = await tts.toFile(outDir, seg.text, PROSODY);
    const target = path.join(outDir, `${seg.name}.mp3`);
    fs.renameSync(audioFilePath, target);
    frames[seg.name] = framesForFile(target);
    const seconds = fs.statSync(target).size / BYTES_PER_SECOND;
    console.log('wrote', target, seconds.toFixed(2) + 's', frames[seg.name] + ' frames');
  }

  const source = `/** Generated by scripts/generate-room-narration.cjs — do not edit by hand. */
export const AUDIO_HEAD_FRAMES = ${AUDIO_HEAD_FRAMES};
export const AUDIO_TAIL_FRAMES = ${AUDIO_TAIL_FRAMES};

export const NARRATION_SCENE_FRAMES = {
  intro: ${frames.intro},
  before: ${frames.before},
  after: ${frames.after},
  reject: ${frames.reject},
} as const;
`;
  fs.writeFileSync(timingPath, source);
  console.log('wrote', timingPath);
})().catch((e) => {
  console.error('FAIL', e);
  process.exit(1);
});
